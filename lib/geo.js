const PLACE_KEYS = Object.keys(PLACE).sort((a, b) => b.length - a.length);
const COUNTY_KEYS = Object.keys(ALIAS).sort((a, b) => b.length - a.length);
const jit = () => (Math.random() - 0.5) * 0.01;

// 回傳 { lng, lat, place, county } 或 null
export function locate(text, defaultCounty) {
  text = text || "";
  for (const k of PLACE_KEYS) {
    if (text.includes(k)) {
      const [lng, lat, county] = PLACE[k];
      return { lng: lng + jit(), lat: lat + jit(), place: k, county };
    }
  }
  for (const k of COUNTY_KEYS) {
    if (text.includes(k)) {
      const county = ALIAS[k];
      const [lng, lat] = COUNTY[county];
      return { lng: lng + jit(), lat: lat + jit(), place: county, county };
    }
  }
  if (defaultCounty && COUNTY[defaultCounty]) {
    const [lng, lat] = COUNTY[defaultCounty];
    return { lng: lng + jit(), lat: lat + jit(), place: defaultCounty, county: defaultCounty };
  }
  return null;
}
