// 政策民生：需有「已定案/已上路」訊號才收，過濾掉研議中與口水
const POLICY_DONE = ["上路", "實施", "施行", "開辦", "核定", "通過", "啟用", "通車", "開放", "公告", "補助", "補貼", "新制", "開徵", "發放", "上線", "啟動"];
// 排除：政治攻防/選舉/人對人喊話/未定/交誼致詞
const EXCLUDE = ["選舉", "參選", "競選", "造勢", "本命區", "輔選", "黨主席", "黨產", "民調", "初選", "提名", "立委參選", "市長參選", "議員參選", "隔空", "互嗆", "互槓", "口水", "喊話", "批評", "回嗆", "嗆", "研議", "擬議", "規劃中", "傳將", "盼", "呼籲中央", "姊妹市", "締結", "締盟", "致詞", "畢業典禮", "畢業生", "追憶", "紀念晚會", "感謝狀", "頒獎", "就職"];
const HARD = ["disaster", "safety", "warning"]; // 即使有政治字眼，只要是真實災安事件就保留

function hit(text, list) {
  return list.some((k) => text.includes(k));
}

export function classify(text, forceCats = []) {
  text = text || "";
  const cats = new Set(forceCats);
  for (const c of ["disaster", "safety", "warning", "ecology", "activity"]) {
    if (hit(text, KW[c])) cats.add(c);
  }
  if (hit(text, POLICY_DONE) && !hit(text, EXCLUDE)) cats.add("policy");

  const hasHard = [...cats].some((c) => HARD.includes(c));
  // 政治口水/選舉/交誼且非真實災安事件 → 丟棄
  if (hit(text, EXCLUDE) && !hasHard) {
    // 仍允許純生態/活動（它們不是政治口水）
    const soft = [...cats].filter((c) => c === "ecology" || c === "activity");
    return soft;
  }
  return [...cats];
}
